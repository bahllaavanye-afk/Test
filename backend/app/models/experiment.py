import uuid
from datetime import datetime
from typing import Any, Dict, List, Optional

from sqlalchemy import String, Numeric, DateTime, JSON, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base


"""ORM model definitions for experiment tracking.

This module contains the :class:`Experiment` model, which stores metadata
about machine‑learning experiments executed by the platform. The model is
persisted using SQLAlchemy and includes fields for configuration, status,
performance metrics, timestamps, and artifact locations.
"""


class Experiment(Base):
    """SQLAlchemy model representing a single experiment run.

    Attributes
    ----------
    id : Mapped[str]
        Primary key; a UUID string generated automatically.
    name : Mapped[str]
        Human‑readable unique name for the experiment.
    config : Mapped[Dict[str, Any]]
        JSON‑serialisable configuration dictionary used to initialise the
        experiment.
    status : Mapped[str]
        Current execution state; one of ``queued``, ``running``, ``done`` or
        ``failed``. Defaults to ``queued``.
    val_accuracy : Mapped[Optional[float]]
        Validation accuracy recorded after training; stored with precision
        ``Numeric(6, 4)``.
    val_sharpe : Mapped[Optional[float]]
        Validation Sharpe ratio; stored with precision ``Numeric(8, 4)``.
    test_sharpe : Mapped[Optional[float]]
        Test‑set Sharpe ratio; stored with precision ``Numeric(8, 4)``.
    artifact_path : Mapped[Optional[str]]
        Filesystem path to model artefacts generated by the experiment.
    started_at : Mapped[Optional[datetime]]
        Timestamp when the experiment started execution.
    completed_at : Mapped[Optional[datetime]]
        Timestamp when the experiment finished (successfully or otherwise).
    error_message : Mapped[Optional[str]]
        Optional error details if the experiment failed.
    metrics_history : Mapped[List[Dict[str, Any]]]
        Chronological list of metric snapshots (e.g. epoch, loss, accuracy)
        captured during training.
    created_at : Mapped[datetime]
        Timestamp when the database record was created.
    """

    __tablename__ = "experiments"

    id: Mapped[str] = mapped_column(
        String, primary_key=True, default=lambda: str(uuid.uuid4())
    )
    name: Mapped[str] = mapped_column(String(128), unique=True, nullable=False)
    config: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    status: Mapped[str] = mapped_column(String(16), default="queued")  # queued|running|done|failed
    val_accuracy: Mapped[Optional[float]] = mapped_column(Numeric(6, 4))
    val_sharpe: Mapped[Optional[float]] = mapped_column(Numeric(8, 4))
    test_sharpe: Mapped[Optional[float]] = mapped_column(Numeric(8, 4))
    artifact_path: Mapped[Optional[str]] = mapped_column(String(512))
    started_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    completed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    error_message: Mapped[Optional[str]] = mapped_column(Text)
    metrics_history: Mapped[List[Dict[str, Any]]] = mapped_column(JSON, default=list)  # [{epoch, loss, acc}, ...]
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)