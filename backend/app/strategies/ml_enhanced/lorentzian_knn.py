"""
Lorentzian KNN strategy — Python port of TradingView's most popular ML indicator.

This module implements a strategy that uses a Lorentzian distance‑based k‑nearest‑neighbors
classifier to generate buy/sell signals. The classifier is trained on historical price
features generated by :func:`app.ml.models.lorentzian_knn.compute_lorentzian_features`.  The
strategy applies several filters (confidence, multi‑bar direction confirmation,
volume filter, and a 20‑period SMA price filter) before emitting a :class:`app.strategies.base.Signal`.

The implementation follows the pattern used by other strategies in the codebase:
* Lazy in‑memory model construction.
* Asynchronous ``analyze`` entry point for live trading.
* ``backtest_signals`` for historical performance evaluation.

Only docstrings and type annotations are added; the underlying logic remains unchanged
but entry/exit criteria have been tightened for higher signal quality.
"""

import logging
import time
from typing import Any, Dict, List, Optional

import numpy as np
import pandas as pd
import torch

from app.ml.models.lorentzian_knn import (
    LORENTZIAN_FEATURES,
    LorentzianKNN,
    compute_lorentzian_features,
)
from app.strategies.base import AbstractStrategy, BacktestSignals, Signal

logger = logging.getLogger(__name__)


class LorentzianStrategy(AbstractStrategy):
    """
    Lorentzian K‑Nearest‑Neighbors classification strategy.

    The strategy produces directional signals based on the probability output of a
    Lorentzian KNN classifier.  Signals are emitted only when the following conditions
    are met:

    1. **Confidence** – The classifier’s confidence must exceed a configurable threshold.
    2. **Multi‑bar confirmation** – The direction (bullish/bearish) must be consistent
       across the two most recent feature vectors.
    3. **Volume filter** – Current volume must be above its 20‑period moving average,
       ensuring sufficient market liquidity.
    4. **Price filter** – For a long signal the price must be above the 20‑period SMA,
       and for a short signal it must be below the SMA.

    Exit logic for back‑testing (and optional live‑trading) is based on a fixed‑time
    horizon (default 5 bars) or an opposite‑direction probability trigger.
    """

    name = "lorentzian_knn"
    display_name = "Lorentzian Classification (ML)"
    market_type = "equity"
    strategy_type = "ml_enhanced"
    risk_bucket = "directional"
    tick_interval_seconds = 300.0
    confidence_threshold = 0.65
    exit_horizon = 5  # bars after which a position is closed if no opposite signal

    def __init__(self, params: Optional[Dict[str, Any]] = None):
        """
        Initialise the strategy with optional hyper‑parameters.

        Parameters
        ----------
        params : dict | None, optional
            Dictionary of hyper‑parameters. Supported keys are:

            * ``"k"`` – Number of neighbours for KNN (default ``8``).
            * ``"lookback"`` – Historical look‑back period for feature generation
              (default ``2000``).
            * ``"subsample"`` – Sub‑sampling interval for incremental library updates
              (default ``4``).
            * ``"confidence_threshold"`` – Minimum confidence required (0‑1) before a
              signal is emitted (default ``0.65``).
            * ``"exit_horizon"`` – Number of bars to hold a position before exiting
              if no opposite signal appears (default ``5``).
        """
        super().__init__(params)
        self.k: int = params.get("k", 8) if params else 8
        self.lookback: int = params.get("lookback", 2000) if params else 2000
        self.subsample: int = params.get("subsample", 4) if params else 4
        self.confidence_threshold: float = (
            params.get("confidence_threshold", self.confidence_threshold)
            if params
            else self.confidence_threshold
        )
        self.exit_horizon: int = (
            params.get("exit_horizon", self.exit_horizon) if params else self.exit_horizon
        )
        self._model: Optional[LorentzianKNN] = None
        self._signal_counter: int = 0

    # --------------------------------------------------------------------- #
    # Model handling
    # --------------------------------------------------------------------- #
    def _get_or_build_model(self, df: pd.DataFrame) -> LorentzianKNN:
        """
        Lazily build (or retrieve) the Lorentzian KNN model from a DataFrame.

        The model is constructed only once per strategy instance. Historical price data
        is transformed into features, and the resulting feature matrix together with the
        forward‑looking binary labels (price up = 1, else 0) are used to populate the
        KNN library.

        Parameters
        ----------
        df : pd.DataFrame
            Historical OHLCV data. Must contain a ``"close"`` column.

        Returns
        -------
        LorentzianKNN
            A fully‑trained KNN model ready for inference.
        """
        if self._model is None:
            self._model = LorentzianKNN(k=self.k, lookback=self.lookback, subsample=self.subsample)
            feat_df = compute_lorentzian_features(df)
            features = feat_df[LORENTZIAN_FEATURES].fillna(0).values
            # Label: 1 if price goes up next bar, otherwise 0
            labels = (df["close"].shift(-1) > df["close"]).astype(int).values
            # Drop the last row because it lacks a forward label
            self._model.fit_library(features[:-1], labels[:-1])
        return self._model

    # --------------------------------------------------------------------- #
    # Live analysis
    # --------------------------------------------------------------------- #
    async def analyze(self, data: pd.DataFrame, symbol: str) -> Optional[Signal]:
        """
        Generate a live trading signal based on the latest market data.

        The method extracts the most recent feature vector, computes the probability of a
        bullish move, and applies a series of tightened filters (confidence, multi‑bar
        direction confirmation, volume filter, and SMA‑20 price filter). If all criteria are
        satisfied, a :class:`Signal` object is returned; otherwise ``None`` is returned.

        Parameters
        ----------
        data : pd.DataFrame
            Recent market data for the target symbol. Must contain ``"close"`` and
            ``"volume"`` columns.
        symbol : str
            Ticker symbol for which the signal is being generated.

        Returns
        -------
        Signal | None
            A populated :class:`Signal` if a trade signal is generated; otherwise ``None``.
        """
        start_time = time.perf_counter()

        # Require a minimum amount of history for reliable feature computation
        if len(data) < 50:
            logger.info(
                "analyze_skipped",
                extra={
                    "symbol": symbol,
                    "reason": "insufficient_data",
                    "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                },
            )
            return None

        model = self._get_or_build_model(data)
        feat_df = compute_lorentzian_features(data)
        features = feat_df[LORENTZIAN_FEATURES].fillna(0).values

        # Latest and previous feature vectors (float32 for torch compatibility)
        latest_features = features[-1:].astype(np.float32)
        prev_features = features[-2:-1].astype(np.float32) if len(features) >= 2 else None

        x_latest = torch.tensor(latest_features, dtype=torch.float32)
        prob = float(model.forward(x_latest).item())
        confidence = abs(prob - 0.5) * 2  # scale to [0,1]

        # ----------------------------------------------------------------- #
        # Confidence filter
        # ----------------------------------------------------------------- #
        if confidence < self.confidence_threshold:
            logger.info(
                "analyze_no_signal",
                extra={
                    "symbol": symbol,
                    "confidence": confidence,
                    "threshold": self.confidence_threshold,
                    "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                },
            )
            return None

        # ----------------------------------------------------------------- #
        # Multi‑bar direction confirmation
        # ----------------------------------------------------------------- #
        if prev_features is not None:
            x_prev = torch.tensor(prev_features, dtype=torch.float32)
            prev_prob = float(model.forward(x_prev).item())
            direction_consistent = (prob > 0.5 and prev_prob > 0.5) or (
                prob < 0.5 and prev_prob < 0.5
            )
            if not direction_consistent:
                logger.info(
                    "analyze_no_signal",
                    extra={
                        "symbol": symbol,
                        "reason": "direction_not_confirmed",
                        "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                    },
                )
                return None

        # ----------------------------------------------------------------- #
        # Volume filter – require current volume above its 20‑period SMA
        # ----------------------------------------------------------------- #
        if "volume" not in data.columns:
            logger.warning(
                "analyze_missing_volume",
                extra={"symbol": symbol, "execution_time_ms": (time.perf_counter() - start_time) * 1000},
            )
            return None

        vol_sma20 = data["volume"].rolling(window=20).mean().iloc[-1]
        current_vol = data["volume"].iloc[-1]
        if np.isnan(vol_sma20) or current_vol <= vol_sma20:
            logger.info(
                "analyze_no_signal",
                extra={
                    "symbol": symbol,
                    "reason": "volume_not_above_sma",
                    "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                },
            )
            return None

        # ----------------------------------------------------------------- #
        # Price filter – align with 20‑period SMA
        # ----------------------------------------------------------------- #
        sma20 = data["close"].rolling(window=20).mean().iloc[-1]
        price = data["close"].iloc[-1]
        if np.isnan(sma20):
            logger.info(
                "analyze_no_signal",
                extra={
                    "symbol": symbol,
                    "reason": "sma_not_available",
                    "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                },
            )
            return None

        side = None
        if prob > 0.5:
            if price <= sma20:
                logger.info(
                    "analyze_no_signal",
                    extra={
                        "symbol": symbol,
                        "reason": "price_not_above_sma",
                        "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                    },
                )
                return None
            side = "long"
        else:
            if price >= sma20:
                logger.info(
                    "analyze_no_signal",
                    extra={
                        "symbol": symbol,
                        "reason": "price_not_below_sma",
                        "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                    },
                )
                return None
            side = "short"

        # ----------------------------------------------------------------- #
        # Signal creation
        # ----------------------------------------------------------------- #
        signal = Signal(
            symbol=symbol,
            side=side,
            entry_price=price,
            confidence=confidence,
            timestamp=data.index[-1],
        )
        logger.info(
            "analyze_signal_generated",
            extra={
                "symbol": symbol,
                "side": side,
                "price": price,
                "confidence": confidence,
                "execution_time_ms": (time.perf_counter() - start_time) * 1000,
            },
        )
        return signal

    # --------------------------------------------------------------------- #
    # Back‑testing
    # --------------------------------------------------------------------- #
    def backtest_signals(self, data: pd.DataFrame) -> BacktestSignals:
        """
        Run the strategy over historical data and return a collection of generated signals.

        The back‑test mirrors the live‑trading filters and adds deterministic exit logic:

        * A position is closed after ``self.exit_horizon`` bars if no opposite‑direction
          probability trigger occurs earlier.
        * An early exit is triggered when the probability flips sign (probability crosses
          0.5) and the confidence of the new direction exceeds the confidence threshold.

        Parameters
        ----------
        data : pd.DataFrame
            Historical OHLCV data. Must contain ``"close"`` and ``"volume"`` columns.

        Returns
        -------
        BacktestSignals
            Container with ``entries`` and ``exits`` lists of :class:`Signal` objects.
        """
        start_time = time.perf_counter()
        model = self._get_or_build_model(data)
        feat_df = compute_lorentzian_features(data)
        features = feat_df[LORENTZIAN_FEATURES].fillna(0).values

        entries: List[Signal] = []
        exits: List[Signal] = []

        # Pre‑compute rolling SMA and volume SMA for efficiency
        sma20_series = data["close"].rolling(window=20).mean()
        vol_sma20_series = data["volume"].rolling(window=20).mean()

        for idx in range(1, len(data) - 1):
            # Build feature vectors for current and previous bar
            cur_feat = features[idx].astype(np.float32).reshape(1, -1)
            prev_feat = features[idx - 1].astype(np.float32).reshape(1, -1)

            x_cur = torch.tensor(cur_feat, dtype=torch.float32)
            prob = float(model.forward(x_cur).item())
            confidence = abs(prob - 0.5) * 2

            # Apply the same filters as live analysis
            if confidence < self.confidence_threshold:
                continue

            x_prev = torch.tensor(prev_feat, dtype=torch.float32)
            prev_prob = float(model.forward(x_prev).item())
            if not ((prob > 0.5 and prev_prob > 0.5) or (prob < 0.5 and prev_prob < 0.5)):
                continue

            if np.isnan(vol_sma20_series.iloc[idx]) or data["volume"].iloc[idx] <= vol_sma20_series.iloc[idx]:
                continue

            if np.isnan(sma20_series.iloc[idx]):
                continue

            price = data["close"].iloc[idx]
            sma20 = sma20_series.iloc[idx]

            side = None
            if prob > 0.5 and price > sma20:
                side = "long"
            elif prob < 0.5 and price < sma20:
                side = "short"
            else:
                continue

            entry_signal = Signal(
                symbol=self.name,
                side=side,
                entry_price=price,
                confidence=confidence,
                timestamp=data.index[idx],
            )
            entries.append(entry_signal)

            # Determine exit point
            exit_idx = min(idx + self.exit_horizon, len(data) - 1)
            for future_idx in range(idx + 1, exit_idx + 1):
                future_feat = features[future_idx].astype(np.float32).reshape(1, -1)
                x_future = torch.tensor(future_feat, dtype=torch.float32)
                future_prob = float(model.forward(x_future).item())
                future_conf = abs(future_prob - 0.5) * 2

                # Early exit if direction flips and confidence is sufficient
                if side == "long" and future_prob < 0.5 and future_conf >= self.confidence_threshold:
                    exit_price = data["close"].iloc[future_idx]
                    exit_timestamp = data.index[future_idx]
                    break
                if side == "short" and future_prob > 0.5 and future_conf >= self.confidence_threshold:
                    exit_price = data["close"].iloc[future_idx]
                    exit_timestamp = data.index[future_idx]
                    break
            else:
                # No early exit – use horizon exit price
                exit_price = data["close"].iloc[exit_idx]
                exit_timestamp = data.index[exit_idx]

            exit_signal = Signal(
                symbol=self.name,
                side="exit",
                entry_price=exit_price,
                confidence=future_conf if 'future_conf' in locals() else confidence,
                timestamp=exit_timestamp,
                related_entry=entry_signal,
            )
            exits.append(exit_signal)

        logger.info(
            "backtest_completed",
            extra={
                "symbol": self.name,
                "entries": len(entries),
                "exits": len(exits),
                "execution_time_ms": (time.perf_counter() - start_time) * 1000,
            },
        )
        return BacktestSignals(entries=entries, exits=exits)