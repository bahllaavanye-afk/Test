"""
Lorentzian KNN strategy — Python port of TradingView's most popular ML indicator.

This module implements a strategy that uses a Lorentzian distance‑based k‑nearest‑neighbors
classifier to generate buy/sell signals. The classifier is trained on historical price
features generated by :func:`app.ml.models.lorentzian_knn.compute_lorentzian_features`.  The
strategy applies several tightened filters (confidence, multi‑bar direction confirmation,
price‑SMA alignment with a small buffer, and a volume sanity check) before emitting a
:class:`app.strategies.base.Signal`.  The exit logic is also refined: a position is
closed when the model’s probability flips sign, the price drifts away from the SMA buffer,
or a maximum holding period is reached.

The implementation follows the pattern used by other strategies in the codebase:
* Lazy in‑memory model construction.
* Asynchronous ``analyze`` entry point for live trading.
* ``backtest_signals`` for historical performance evaluation.

Only docstrings and type annotations are added; the underlying logic remains unchanged
except for the enhancements described above.
"""

import logging
import time
from typing import Any, Dict, List, Optional

import numpy as np
import pandas as pd
import torch

from app.ml.models.lorentzian_knn import (
    LORENTZIAN_FEATURES,
    LorentzianKNN,
    compute_lorentzian_features,
)
from app.strategies.base import AbstractStrategy, BacktestSignals, Signal

logger = logging.getLogger(__name__)


class LorentzianStrategy(AbstractStrategy):
    """
    Lorentzian K‑Nearest‑Neighbors classification strategy.

    Attributes
    ----------
    name : str
        Internal identifier used by the platform.
    display_name : str
        Human‑readable name shown in UI components.
    market_type : str
        The market category this strategy is intended for (e.g., ``"equity"``).
    strategy_type : str
        Classification of the strategy; here it is ``"ml_enhanced"``.
    risk_bucket : str
        Risk bucket label for portfolio construction.
    tick_interval_seconds : float
        Expected data tick interval.
    confidence_threshold : float
        Minimum confidence required (0‑1) before a signal is emitted.
    sma_buffer : float
        Minimum fractional distance between price and SMA20 for entry (e.g., 0.001 = 0.1%).
    max_holding_bars : int
        Upper bound on holding period for back‑test signals.
    """

    name = "lorentzian_knn"
    display_name = "Lorentzian Classification (ML)"
    market_type = "equity"
    strategy_type = "ml_enhanced"
    risk_bucket = "directional"
    tick_interval_seconds = 300.0
    confidence_threshold = 0.70  # tightened from 0.65
    sma_buffer = 0.001  # 0.1 %
    max_holding_bars = 30

    def __init__(self, params: Optional[Dict[str, Any]] = None):
        """
        Initialise the strategy with optional hyper‑parameters.

        Parameters
        ----------
        params : dict | None, optional
            Dictionary of hyper‑parameters. Supported keys are:

            * ``"k"`` – Number of neighbours for KNN (default ``8``).
            * ``"lookback"`` – Historical look‑back period for feature generation
              (default ``2000``).
            * ``"subsample"`` – Sub‑sampling interval for incremental library updates
              (default ``4``).
            * ``"confidence_threshold"`` – Override default confidence threshold.
            * ``"sma_buffer"`` – Override SMA distance buffer.
            * ``"max_holding_bars"`` – Override maximum holding period.
        """
        super().__init__(params)
        self.k: int = params.get("k", 8) if params else 8
        self.lookback: int = params.get("lookback", 2000) if params else 2000
        self.subsample: int = params.get("subsample", 4) if params else 4
        if params:
            self.confidence_threshold = params.get("confidence_threshold", self.confidence_threshold)
            self.sma_buffer = params.get("sma_buffer", self.sma_buffer)
            self.max_holding_bars = params.get("max_holding_bars", self.max_holding_bars)

        self._model: Optional[LorentzianKNN] = None
        self._signal_counter: int = 0

    # --------------------------------------------------------------------- #
    # Model handling
    # --------------------------------------------------------------------- #
    def _get_or_build_model(self, df: pd.DataFrame) -> LorentzianKNN:
        """
        Lazily build (or retrieve) the Lorentzian KNN model from a DataFrame.

        The model is constructed only once per strategy instance. Historical price data
        is transformed into features, and the resulting feature matrix together with the
        forward‑looking binary labels (price up = 1, else 0) are used to populate the
        KNN library.

        Parameters
        ----------
        df : pd.DataFrame
            Historical OHLCV data. Must contain a ``"close"`` column.

        Returns
        -------
        LorentzianKNN
            A fully‑trained KNN model ready for inference.
        """
        if self._model is None:
            self._model = LorentzianKNN(k=self.k, lookback=self.lookback, subsample=self.subsample)
            feat_df = compute_lorentzian_features(df)
            features = feat_df[LORENTZIAN_FEATURES].fillna(0).values
            # Label: 1 if price goes up next bar
            labels = (df["close"].shift(-1) > df["close"]).astype(int).values
            # Drop the last row because it lacks a forward label
            self._model.fit_library(features[:-1], labels[:-1])
        return self._model

    # --------------------------------------------------------------------- #
    # Helper filters
    # --------------------------------------------------------------------- #
    def _confidence(self, prob: float) -> float:
        """Return a symmetric confidence measure in the range [0, 1]."""
        return abs(prob - 0.5) * 2

    def _price_sma_condition(self, price: float, sma20: float, direction: str) -> bool:
        """
        Verify that price is sufficiently away from SMA20 in the direction of the trade.

        Parameters
        ----------
        price : float
            Current close price.
        sma20 : float
            20‑period simple moving average.
        direction : {"long", "short"}
            Desired trade direction.

        Returns
        -------
        bool
            True if condition is satisfied.
        """
        if direction == "long":
            return price > sma20 * (1 + self.sma_buffer)
        else:
            return price < sma20 * (1 - self.sma_buffer)

    def _volume_sanity(self, volume_series: pd.Series) -> bool:
        """
        Simple volume sanity check – ensure the latest volume is not an extreme outlier
        (e.g., a sudden zero‑volume data glitch). The check passes if the latest volume
        is at least 10 % of the median of the last 20 periods.

        Parameters
        ----------
        volume_series : pd.Series
            Series of volume values.

        Returns
        -------
        bool
            True if volume is acceptable.
        """
        recent = volume_series.tail(20)
        median = recent.median()
        latest = volume_series.iloc[-1]
        return median > 0 and latest >= 0.1 * median

    # --------------------------------------------------------------------- #
    # Live analysis
    # --------------------------------------------------------------------- #
    async def analyze(self, data: pd.DataFrame, symbol: str) -> Optional[Signal]:
        """
        Generate a live trading signal based on the latest market data.

        The method extracts the most recent feature vector, computes the probability of a
        bullish move, and applies a series of tightened filters (confidence, multi‑bar
        direction confirmation, SMA‑20 price buffer, and volume sanity). If all criteria
        are satisfied, a :class:`Signal` object is returned; otherwise ``None`` is returned.

        Parameters
        ----------
        data : pd.DataFrame
            Recent market data for the target symbol. Must contain ``"close"`` and ``"volume"``
            columns.
        symbol : str
            Ticker symbol for which the signal is being generated.

        Returns
        -------
        Signal | None
            A populated :class:`Signal` if a trade signal is generated; otherwise ``None``.
        """
        start_time = time.perf_counter()
        if len(data) < 50:
            logger.info(
                "analyze_skipped",
                extra={
                    "symbol": symbol,
                    "reason": "insufficient_data",
                    "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                },
            )
            return None

        model = self._get_or_build_model(data)
        feat_df = compute_lorentzian_features(data)
        features = feat_df[LORENTZIAN_FEATURES].fillna(0).values

        # Latest and previous feature vectors
        latest_features = features[-1:].astype(np.float32)
        prev_features = features[-2:-1].astype(np.float32) if len(features) >= 2 else None
        prev2_features = features[-3:-2].astype(np.float32) if len(features) >= 3 else None

        x_latest = torch.tensor(latest_features, dtype=torch.float32)
        prob = float(model.forward(x_latest).item())
        confidence = self._confidence(prob)

        if confidence < self.confidence_threshold:
            logger.info(
                "analyze_no_signal",
                extra={
                    "symbol": symbol,
                    "confidence": confidence,
                    "threshold": self.confidence_threshold,
                    "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                },
            )
            return None

        # Multi‑bar direction confirmation (at least two consecutive bars)
        if prev_features is not None:
            x_prev = torch.tensor(prev_features, dtype=torch.float32)
            prev_prob = float(model.forward(x_prev).item())
            if (prob > 0.5) != (prev_prob > 0.5):
                logger.info(
                    "analyze_no_signal",
                    extra={
                        "symbol": symbol,
                        "reason": "direction_not_confirmed",
                        "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                    },
                )
                return None
        if prev2_features is not None:
            x_prev2 = torch.tensor(prev2_features, dtype=torch.float32)
            prev2_prob = float(model.forward(x_prev2).item())
            if (prob > 0.5) != (prev2_prob > 0.5):
                logger.info(
                    "analyze_no_signal",
                    extra={
                        "symbol": symbol,
                        "reason": "direction_not_confirmed_two_bars",
                        "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                    },
                )
                return None

        # Volume sanity check
        if "volume" in data.columns and not self._volume_sanity(data["volume"]):
            logger.info(
                "analyze_no_signal",
                extra={
                    "symbol": symbol,
                    "reason": "volume_sanity_failed",
                    "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                },
            )
            return None

        # Price‑SMA20 filter with buffer
        sma20 = data["close"].rolling(window=20).mean().iloc[-1]
        price = data["close"].iloc[-1]
        if np.isnan(sma20):
            logger.info(
                "analyze_no_signal",
                extra={
                    "symbol": symbol,
                    "reason": "sma_not_available",
                    "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                },
            )
            return None

        if prob > 0.5:
            if not self._price_sma_condition(price, sma20, "long"):
                logger.info(
                    "analyze_no_signal",
                    extra={
                        "symbol": symbol,
                        "reason": "price_not_above_sma_buffer",
                        "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                    },
                )
                return None
            side = "buy"
        else:
            if not self._price_sma_condition(price, sma20, "short"):
                logger.info(
                    "analyze_no_signal",
                    extra={
                        "symbol": symbol,
                        "reason": "price_not_below_sma_buffer",
                        "execution_time_ms": (time.perf_counter() - start_time) * 1000,
                    },
                )
                return None
            side = "sell"

        # Build and return the signal
        self._signal_counter += 1
        signal = Signal(
            symbol=symbol,
            side=side,
            timestamp=data.index[-1],
            price=price,
            confidence=confidence,
            model_probability=prob,
            id=self._signal_counter,
        )
        logger.info(
            "analyze_signal_generated",
            extra={
                "symbol": symbol,
                "side": side,
                "price": price,
                "confidence": confidence,
                "probability": prob,
                "execution_time_ms": (time.perf_counter() - start_time) * 1000,
            },
        )
        return signal

    # --------------------------------------------------------------------- #
    # Back‑test support
    # --------------------------------------------------------------------- #
    def backtest_signals(self, data: pd.DataFrame, symbol: str) -> BacktestSignals:
        """
        Generate signals for a historical data series.

        The back‑test mirrors the live logic but also produces exit timestamps. A position
        is closed when any of the following occurs:

        * The model probability flips sign (e.g., bullish → bearish).
        * The price moves outside the SMA‑20 buffer.
        * The holding period exceeds ``max_holding_bars``.

        Parameters
        ----------
        data : pd.DataFrame
            Historical OHLCV data with at least ``"close"`` and ``"volume"`` columns.
        symbol : str
            Ticker symbol.

        Returns
        -------
        BacktestSignals
            Container holding all entry/exit signals for the given symbol.
        """
        start_time = time.perf_counter()
        model = self._get_or_build_model(data)
        feat_df = compute_lorentzian_features(data)
        features = feat_df[LORENTZIAN_FEATURES].fillna(0).values

        signals: List[Signal] = []
        open_signal: Optional[Signal] = None
        open_index: Optional[int] = None

        for idx in range(len(data)):
            # Need at least three rows for multi‑bar confirmation
            if idx < 2:
                continue

            # Feature slice up to current bar (inclusive)
            cur_features = features[idx : idx + 1].astype(np.float32)
            prob = float(model.forward(torch.tensor(cur_features, dtype=torch.float32)).item())
            confidence = self._confidence(prob)

            if confidence < self.confidence_threshold:
                continue

            # Multi‑bar confirmation
            prev_prob = float(
                model.forward(
                    torch.tensor(features[idx - 1 : idx].astype(np.float32), dtype=torch.float32)
                ).item()
            )
            prev2_prob = float(
                model.forward(
                    torch.tensor(features[idx - 2 : idx - 1].astype(np.float32), dtype=torch.float32)
                ).item()
            )
            if (prob > 0.5) != (prev_prob > 0.5) or (prob > 0.5) != (prev2_prob > 0.5):
                continue

